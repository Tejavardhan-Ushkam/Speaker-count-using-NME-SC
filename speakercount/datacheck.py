"""`check-data` and `make-splits`."""

from __future__ import annotations

from collections import Counter
from pathlib import Path

import numpy as np

from .config import ROOT, load_config, resolve_path
from .rttm import read_rttm, speaker_count

# (label, audio dir, rttm dir, k_max of that corpus)
LAYOUT = [
    ("AMI train", "dataset/train", "dataset/rttms/train", 10),
    ("AMI dev", "dataset/dev", "dataset/rttms/dev", 10),
    ("AMI test", "dataset/test", "dataset/rttms/test", 10),
    ("VoxConverse dev", "dataset/voxconverse/audio/dev", "dataset/voxconverse/rttm/dev", 25),
    ("VoxConverse test", "dataset/voxconverse/audio/test", "dataset/voxconverse/rttm/test", 25),
]

K_BINS = [(1, 1, "1"), (2, 2, "2"), (3, 4, "3-4"), (5, 7, "5-7"), (8, 10**6, "8+")]


def k_bin(k: int) -> str:
    for lo, hi, name in K_BINS:
        if lo <= k <= hi:
            return name
    raise ValueError(k)


def _hist(ks) -> str:
    c = Counter(ks)
    return ", ".join(f"K={k}:{c[k]}" for k in sorted(c))


def _scan(audio_dir: Path, rttm_dir: Path):
    wavs = {p.stem: p for p in audio_dir.glob("*.wav")} if audio_dir.is_dir() else {}
    rttms = {p.stem: p for p in rttm_dir.glob("*.rttm")} if rttm_dir.is_dir() else {}
    ks, speech, dur = {}, {}, {}
    for rec, p in rttms.items():
        turns = read_rttm(p)
        ks[rec] = speaker_count(turns)
        spans = sorted((t.start, t.end) for t in turns)
        tot, cur_s, cur_e = 0.0, None, None
        for s, e in spans:
            if cur_e is None or s > cur_e:
                if cur_e is not None:
                    tot += cur_e - cur_s
                cur_s, cur_e = s, e
            else:
                cur_e = max(cur_e, e)
        if cur_e is not None:
            tot += cur_e - cur_s
        speech[rec] = tot
    try:
        import soundfile as sf

        for rec, p in wavs.items():
            info = sf.info(str(p))
            dur[rec] = info.frames / info.samplerate
    except Exception as exc:  # noqa: BLE001
        print(f"  (could not probe audio durations: {exc})")
    return wavs, rttms, ks, speech, dur


def check_data() -> bool:
    lines = ["# Data summary", "", "Generated by `python run.py check-data`.", ""]
    lines += ["| Split | wav | rttm | matched | hours (audio) | speech h (RTTM union) | K histogram | max K | k_max | ok |",
              "|---|---|---|---|---|---|---|---|---|---|"]
    ok_all = True
    problems = []
    for label, a, r, kmax in LAYOUT:
        wavs, rttms, ks, speech, dur = _scan(ROOT / a, ROOT / r)
        matched = set(wavs) & set(rttms)
        ok = bool(rttms) and len(matched) == len(rttms) == len(wavs)
        maxk = max(ks.values()) if ks else 0
        if maxk > kmax:
            ok = False
            problems.append(f"{label}: max K {maxk} > k_max {kmax}")
        if not ok:
            ok_all = False
            problems.append(
                f"{label}: {len(wavs)} wav in {a}, {len(rttms)} rttm in {r}, {len(matched)} matched"
            )
        hours = sum(dur.values()) / 3600 if dur else float("nan")
        sp = sum(speech.values()) / 3600 if speech else float("nan")
        lines.append(
            f"| {label} | {len(wavs)} | {len(rttms)} | {len(matched)} | {hours:.1f} | {sp:.1f} | "
            f"{_hist(ks.values())} | {maxk} | {kmax} | {'yes' if ok else '**NO**'} |"
        )
        print(f"{label:18s} wav={len(wavs):4d} rttm={len(rttms):4d} matched={len(matched):4d} "
              f"hours={hours:6.1f}  {_hist(ks.values())}")

    # VoxConverse splits, if already made
    split_lines = []
    for role in ("train", "val"):
        f = ROOT / "splits" / f"voxconverse_{role}.txt"
        if f.exists():
            cfg = load_config(f"configs/vox_{role}.yaml")
            recs = [x.strip() for x in f.read_text().splitlines() if x.strip()]
            kk = [speaker_count(read_rttm(resolve_path(cfg.dataset.rttm_dir) / f"{x}.rttm")) for x in recs]
            split_lines.append(f"| Vox {role} | {len(recs)} | {_hist(kk)} | "
                               f"{_hist([k_bin(k) for k in kk]).replace('K=', '')} |")
    if split_lines:
        lines += ["", "## VoxConverse 80/20 split (by recording, stratified by K bin, seed 0)", "",
                  "| Split | recordings | K histogram | K-bin histogram |", "|---|---|---|---|"] + split_lines

    lines += ["", "Mode baseline (always predict the training mode) and ambiguous-segment fractions are "
              "added in later phases.", ""]
    if problems:
        lines += ["## Problems", ""] + [f"- {p}" for p in problems]
    out = ROOT / "results" / "data_summary.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    if problems:
        print("PROBLEMS:\n  " + "\n  ".join(problems))
    return ok_all


def make_splits(seed: int = 0, val_frac: float = 0.2) -> None:
    rttm_dir = ROOT / "dataset/voxconverse/rttm/dev"
    recs = sorted(p.stem for p in rttm_dir.glob("*.rttm"))
    if not recs:
        raise FileNotFoundError(f"no RTTMs in {rttm_dir}")
    ks = {r: speaker_count(read_rttm(rttm_dir / f"{r}.rttm")) for r in recs}
    rng = np.random.default_rng(seed)
    train, val = [], []
    for _, _, name in K_BINS:
        members = sorted(r for r in recs if k_bin(ks[r]) == name)
        if not members:
            continue
        perm = [members[i] for i in rng.permutation(len(members))]
        n_val = int(round(val_frac * len(members)))
        val += perm[:n_val]
        train += perm[n_val:]
    out = ROOT / "splits"
    out.mkdir(exist_ok=True)
    (out / "voxconverse_train.txt").write_text("\n".join(sorted(train)) + "\n")
    (out / "voxconverse_val.txt").write_text("\n".join(sorted(val)) + "\n")
    for name, part in (("train", train), ("val", val)):
        print(f"voxconverse_{name}: {len(part)} recordings  {_hist(ks[r] for r in part)}  "
              f"bins: {_hist(k_bin(ks[r]) for r in part).replace('K=', '')}")
